import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const rows=JSON.parse(readFileSync(new URL('worker/locales/messages.json',root),'utf8'));
const core=JSON.parse(readFileSync(new URL('worker/locales/core.json',root),'utf8'));
const catalog={...core};const errors=[];
for(const row of rows){if(catalog[row.key])errors.push('Duplicate key: '+row.key);catalog[row.key]={'zh-TW':row['zh-TW'],en:row.en};}
for(const [key,value] of Object.entries(catalog)){
 for(const locale of ['zh-TW','en'])if(typeof value[locale]!=='string'||!value[locale].trim())errors.push('Missing '+locale+': '+key);
 const params=s=>[...s.matchAll(/\{([A-Za-z][\w]*)\}/g)].map(x=>x[1]).sort().join(',');
 if(params(value.en||'')!==params(value['zh-TW']||''))errors.push('Parameter mismatch: '+key);
}
if(errors.length)throw Error(errors.join('\n'));
writeFileSync(new URL('worker/i18n-catalog.js',root),'// Generated by scripts/compile-i18n.mjs; edit worker/locales/*.json.\nexport const i18nCatalog='+JSON.stringify(catalog)+';\n');
console.log('Validated '+Object.keys(catalog).length+' bilingual entries.');
